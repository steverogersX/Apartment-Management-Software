import { z } from "zod";

export type InventoryUnit = "Pcs" | "Box" | "Litre" | "Kg" | "Set" | "Roll";

export type InventoryItem = {
  id: string;
  name: string;
  category: string;
  unit: InventoryUnit;
  currentStock: number;
  reorderLevel: number;
  store: string;
};

export const editInventoryItemSchema = z.object({
  name: z.string().min(2, "Name must be at least 2 characters"),
  category: z.string().min(2, "Category is required"),
  unit: z.enum(["Pcs", "Box", "Litre", "Kg", "Set", "Roll"]),
  currentStock: z.coerce.number().min(0, "Stock must be >= 0"),
  reorderLevel: z.coerce.number().min(0, "Reorder level must be >= 0"),
  store: z.string().min(2, "Store is required"),
});

export type EditInventoryItemInput = z.infer<typeof editInventoryItemSchema>;

export type StockTransactionType = "Stock In" | "Stock Out" | "Staff Allotment";

export type StockTransaction = {
  id: string;
  itemId: string;
  date: string;
  type: StockTransactionType;
  quantity: number;
  balanceAfter: number;
  reason: string;
  allottedTo?: string;
  recordedBy: string;
};

export const addStockTransactionSchema = z.object({
  type: z.enum(["Stock In", "Stock Out", "Staff Allotment"]),
  quantity: z.coerce.number().min(1, "Quantity must be at least 1"),
  reason: z.string().min(2, "Reason is required"),
  allottedTo: z.string().optional(),
});

export type AddStockTransactionInput = z.infer<typeof addStockTransactionSchema>;

