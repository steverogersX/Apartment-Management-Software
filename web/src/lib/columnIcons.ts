import {
  Bell,
  Building2,
  Calendar,
  Car,
  CircleDot,
  Clock,
  FileText,
  Flag,
  Hash,
  Home,
  IndianRupee,
  Landmark,
  LogIn,
  LogOut,
  Mail,
  MapPin,
  Package,
  Paperclip,
  Phone,
  Ruler,
  ShieldCheck,
  SquareParking,
  Tag,
  Tags,
  UserRound,
  Users,
  Wrench,
  type LucideIcon,
} from "lucide-react";

const RULES: [RegExp, LucideIcon][] = [
  [/check[\s-]?in/, LogIn],
  [/check[\s-]?out/, LogOut],
  [/#|receipt|certificate|ifsc|account number|id proof|share nos|^pass$|^ticket$/, Hash],
  [
    /amount|total|cost|wage|balance|collected|outstanding|interest|variance|unreconciled/,
    IndianRupee,
  ],
  [/date|paid on|move-in|raised|term |added on|period|last (updated|visit)/, Calendar],
  [/time|shift|last active/, Clock],
  [/flats served|audience|members/, Users],
  [/flat/, Home],
  [/tower|floor|society/, Building2],
  [/location|store/, MapPin],
  [/status|occupancy/, CircleDot],
  [/phone|contact/, Phone],
  [/email/, Mail],
  [/role|designation|position|permissions|warranty/, ShieldCheck],
  [/vehicle|registration/, Car],
  [/slot/, SquareParking],
  [/account|ledger|institution/, Landmark],
  [/priority/, Flag],
  [/attachments/, Paperclip],
  [/tags/, Tags],
  [/reminders/, Bell],
  [/maintenance/, Wrench],
  [/size/, Ruler],
  [/item|asset|stock|reorder/, Package],
  [/type|category|module|scope|source|head|mode|action|entity/, Tag],
  [/notice|meeting|issue|detail|narration|work done|minutes/, FileText],
  [
    /name|resident|member|owner|tenant|holder|nominee|visitor|staff|provider|vendor|witness| by$|assigned to/,
    UserRound,
  ],
];

export function iconForColumnLabel(label: string): LucideIcon | undefined {
  const key = label.toLowerCase();
  return RULES.find(([pattern]) => pattern.test(key))?.[1];
}
