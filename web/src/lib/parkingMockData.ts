import { z } from "zod";

/**
 * Parking is allotted per flat, the way Indian societies run it: a slot belongs to one flat at a
 * time, and that flat parks its own vehicles in it. What physically fits is set by the bay type —
 * a standard car bay usually has room for a two-wheeler and a cycle beside the car.
 */

export type ParkingVehicleType = "car" | "two_wheeler" | "cycle";

export const PARKING_VEHICLE_TYPES: ParkingVehicleType[] = ["car", "two_wheeler", "cycle"];

export type ParkingBayType = "car" | "tandem" | "two_wheeler";

export const PARKING_BAYS: Record<
  ParkingBayType,
  { label: string; hint: string; fits: Record<ParkingVehicleType, number> }
> = {
  car: {
    label: "Car bay",
    hint: "1 car, with room for a two-wheeler and a cycle beside it",
    fits: { car: 1, two_wheeler: 1, cycle: 1 },
  },
  tandem: {
    label: "Tandem bay",
    hint: "2 cars one behind the other, plus a two-wheeler and a cycle",
    fits: { car: 2, two_wheeler: 1, cycle: 1 },
  },
  two_wheeler: {
    label: "Two-wheeler bay",
    hint: "2 two-wheelers and 2 cycles — no car",
    fits: { car: 0, two_wheeler: 2, cycle: 2 },
  },
};

export const PARKING_BAY_TYPES = Object.keys(PARKING_BAYS) as ParkingBayType[];

export type ParkedVehicle = {
  id: string;
  type: ParkingVehicleType;
  // Cycles aren't registered, so they have no number.
  reg: string | null;
  ownerName: string;
};

export type ParkingAllotment = {
  flatId: string;
  flatLabel: string;
  residentName: string;
  allottedOn: string;
};

export type ParkingSlotRecord = {
  id: string;
  slotNumber: string;
  zone: string;
  bay: ParkingBayType;
  allotment: ParkingAllotment | null;
  vehicles: ParkedVehicle[];
};

export type ParkingSlotAction = "allotted" | "released" | "vehicle_added" | "vehicle_removed";

export type ParkingSlotEvent = {
  id: string;
  slotId: string;
  action: ParkingSlotAction;
  flatLabel: string;
  personName: string;
  vehicle?: Omit<ParkedVehicle, "id">;
  actorName: string;
  timestamp: string;
};

export const addParkingSlotSchema = z.object({
  slotNumber: z.string().min(1, "Slot number is required"),
  zone: z.string().min(1, "Zone is required"),
  bay: z.enum(["car", "tandem", "two_wheeler"]),
});

export type AddParkingSlotInput = z.infer<typeof addParkingSlotSchema>;

export function roomFor(slot: ParkingSlotRecord, type: ParkingVehicleType): number {
  const parked = slot.vehicles.filter((v) => v.type === type).length;
  return Math.max(0, PARKING_BAYS[slot.bay].fits[type] - parked);
}

